"""One-shot generator: embed assets/logo_header.png as a data-URI module.

Run from dashboard_app/assets/:
    ../../.venv  ../../  # noqa
    /Users/hoangminhlong/my-quantitative/.venv/bin/python make_logo_module.py
Writes ../logo.py (committed) so page.py can show the logo with no
file dependency inside the frozen app.
"""

import base64
import os

here = os.path.dirname(os.path.abspath(__file__))
png = os.path.join(here, "logo_header.png")
out = os.path.join(here, "..", "logo.py")

uri = "data:image/png;base64," + base64.b64encode(open(png, "rb").read()).decode()

lines = [uri[i : i + 96] for i in range(0, len(uri), 96)]
src = (
    '"""Owner logo (portrait photo) embedded as a PNG data URI.\n\n'
    "Generated by assets/make_logo_module.py from assets/logo_header.png\n"
    '(51x112). Used only for the dashboard header; the app icon lives in\n'
    'assets/AppIcon.icns."""\n\n'
    "LOGO_DATA_URI = (\n    \"" + '"\n    "'.join(lines) + '"\n)\n'
)
with open(out, "w", encoding="utf-8") as fh:
    fh.write(src)
print("logo.py written, base64 length:", len(uri))
