"""SHV1 G1 - canonical registry truth (tests/test_cycle_registry.py).

MDP-V1 M0: these are INVARIANT tests, not transient-state assertions. The
suite must pass for ANY legitimate registry content — legitimate lifecycle
progress (a cycle pausing, resuming, closing, or a new cycle registering)
must never break governance. Nothing here asserts a specific cycle name,
lifecycle, head or active set; the shape of the law is asserted instead:

- schema validity of every record (validated on every load, re-asserted);
- exact resolution (a recorded id resolves to itself; anything else raises);
- unique cycle IDs;
- active/closed disjointness and terminal absorption (a terminal cycle never
  re-enters the active set — enforced by the transition table);
- terminal-GO-death (P-8: no GO phrase survives its cycle's close — enforced
  by the writer on every transition to TERMINAL);
- projection equality (plans/ACTIVE_CYCLES.json byte-equals the deterministic
  regeneration from canonical NON-TERMINAL records).

All mutation-path tests run on sandbox fixtures. The live-tree checks read
the committed registry and tolerate the projection being regenerated by the
writer (they never hard-code cycle names).
"""
from __future__ import annotations

