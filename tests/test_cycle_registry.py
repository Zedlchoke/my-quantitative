PROJECTION = REPO / "plans" / "ACTIVE_CYCLES.json"


# ----------------------------------------------------------------- helpers

def _cycle_record(cycle_id="TEST-C1", lifecycle="ACTIVE_LIGHT", **over):
    rec = {
        "cycle_id": cycle_id, "asset": "crypto", "plan": "plans/PLAN_test.md",
        "lifecycle": lifecycle, "phase": "P0",
        "integration_worktree": "/tmp/x", "branch": "orca/x",
        "head": "a" * 40, "budget": {"used": 0, "max": 1},
        "denominators": {"asset_published": 0, "asset_observed": 0},
        "s0": "OPEN", "s1": "SEALED_UNTOUCHED", "go_phrase": "",
        "go_phrase_state": "", "workers": 0, "active_heavy": False,
        "lock": "free", "heartbeat_utc": "2026-09-08T00:00:00Z",
        "hard_stop_reason": None, "pause_packet": None,
        "next_authorized_action": "", "updated_at_utc": "2026-09-08T00:00:00Z",
    }
    rec.update(over)
    return rec


def _minimal_registry(*cycles):
    return {
        "schema": cycle_registry.SCHEMA_ID,
        "updated_at_utc": "2026-09-08T00:00:00Z",
        "writer": "test",
        "write_token": None,
        "cycles": list(cycles) or [_cycle_record()],
    }


# --------------------------------------------- invariants over ANY registry

def test_live_registry_schema_valid_and_unique_ids():
    """Every committed record is schema-valid and cycle IDs are unique."""
    reg = cycle_registry.load(REGISTRY)  # load validates every record (fail closed)
    cycle_registry.validate_registry(reg)
    ids = [c["cycle_id"] for c in reg["cycles"]]
    assert len(ids) == len(set(ids)), f"duplicate cycle_ids in the canonical registry: {ids}"
    for rec in reg["cycles"]:
        assert rec["lifecycle"] in cycle_registry.LIFECYCLE
        assert cycle_registry._HEX40.match(rec["head"])
        assert isinstance(rec["budget"]["used"], int) and isinstance(rec["budget"]["max"], int)


def test_exact_resolution_is_total_and_case_sensitive():
    """A recorded id resolves to exactly its own record; anything else —
    including a case-mutated id — raises. Never a guess, never a prefix."""
    reg = cycle_registry.load(REGISTRY)
    for rec in reg["cycles"]:
        resolved = cycle_registry.resolve(reg, rec["cycle_id"])
        assert resolved is rec, "resolution must return the exact record object"
    with pytest.raises(cycle_registry.CycleNotFound):
        cycle_registry.resolve(reg, "DEFINITELY-NOT-A-CYCLE")
    for rec in reg["cycles"]:
        mutated = (rec["cycle_id"][::-1] if rec["cycle_id"].swapcase() == rec["cycle_id"]
                   else rec["cycle_id"].swapcase())
        if mutated != rec["cycle_id"]:
            with pytest.raises(cycle_registry.CycleNotFound):
                cycle_registry.resolve(reg, mutated)  # case-sensitive exact ids


def test_active_and_closed_are_disjoint_over_any_content():
    """No cycle is ever both dispatchable/paused and closed; the partition
    holds for any legitimate registry content."""
    reg = cycle_registry.load(REGISTRY)
    active = {c["cycle_id"] for c in cycle_registry.active_cycles(reg)}
    closed = {c["cycle_id"] for c in cycle_registry.closed_cycles(reg)}
    assert active.isdisjoint(closed)
    assert active | closed <= {c["cycle_id"] for c in reg["cycles"]}
    for rec in reg["cycles"]:
        if rec["lifecycle"] in cycle_registry.CLOSED:
            assert rec["cycle_id"] not in active, "terminal absorption violated"
        elif rec["lifecycle"] in cycle_registry.DISPATCHABLE or rec["lifecycle"] in cycle_registry.PAUSED:
            assert rec["cycle_id"] not in closed


def test_terminal_is_absorbing_no_transition_reopens_history():
    """History is append-only: TERMINAL has an empty out-edge set, and every
    non-terminal lifecycle can close — a closed cycle can never re-enter the
    active set through any writer."""
    assert cycle_registry.ALLOWED_TRANSITIONS["TERMINAL"] == set()
    for lifecycle, edges in cycle_registry.ALLOWED_TRANSITIONS.items():
        if lifecycle != "TERMINAL":
            assert "TERMINAL" in edges, f"{lifecycle} must be closable"
            assert lifecycle not in edges or lifecycle == "TERMINAL"
    reg = _minimal_registry(_cycle_record(lifecycle="TERMINAL"))
    for reopen in ("ACTIVE_LIGHT", "ACTIVE_HEAVY", "PAUSED_MAINTENANCE", "PLANNED_NOT_STARTED"):
        with pytest.raises(cycle_registry.IllegalTransition):
            cycle_registry.transition(reg, "TEST-C1", reopen, reason="rescue")


def test_terminal_go_death_enforced_by_writer():
    """P-8 / RULES §7: a GO phrase never survives its cycle's close. The
    invariant is enforced by the writer on every transition to TERMINAL."""
    for opening in ("PLANNED_NOT_STARTED", "ACTIVE_LIGHT", "ACTIVE_HEAVY",
                    "PAUSED_RESOURCE_CONFLICT", "PAUSED_MAINTENANCE", "BLOCKED"):
        reg = _minimal_registry(_cycle_record(
            lifecycle=opening,
            go_phrase="GO TEST SCORED EXECUTION",
            go_phrase_state="REGISTERED_NOT_CONSUMED",
            hard_stop_reason="X" if opening == "PAUSED_MAINTENANCE" else None,
        ))
        cycle_registry.transition(reg, "TEST-C1", "TERMINAL", reason="close")
        rec = cycle_registry.resolve(reg, "TEST-C1")
        assert rec["go_phrase_state"].startswith("DEAD"), (
            f"closing from {opening} must kill the GO phrase state (P-8)"
        )
        assert rec["lifecycle"] == "TERMINAL"


def test_paused_maintenance_records_why():
    """Content-agnostic: a PAUSED_MAINTENANCE cycle must say why it stopped
    and name its pause packet; any hard_stop_reason value is legitimate."""
    reg = cycle_registry.load(REGISTRY)
    for rec in reg["cycles"]:
        if rec["lifecycle"] == "PAUSED_MAINTENANCE":
            assert rec["hard_stop_reason"], f"{rec['cycle_id']}: paused without a reason"
            assert rec["pause_packet"], f"{rec['cycle_id']}: paused without a pause packet"


def test_validator_rejects_drifted_shapes():
    bad = _minimal_registry()
    bad["schema"] = "cycle_registry@0"
    with pytest.raises(atomic_io.SchemaValidationError):
        cycle_registry.validate_registry(bad)
    bad = _minimal_registry()
    bad["cycles"][0]["head"] = "not-a-sha"
    with pytest.raises(atomic_io.SchemaValidationError):
        cycle_registry.validate_registry(bad)
    bad = _minimal_registry()
    bad["cycles"][0]["budget"] = {"used": 5, "max": 1}
    with pytest.raises(atomic_io.SchemaValidationError):
        cycle_registry.validate_registry(bad)
    bad = _minimal_registry()
    bad["cycles"][0]["s1"] = "OPENED"
    with pytest.raises(atomic_io.SchemaValidationError):
        cycle_registry.validate_registry(bad)
    bad = _minimal_registry(_cycle_record(), _cycle_record(cycle_id="TEST-C1"))
    with pytest.raises(atomic_io.SchemaValidationError):
        cycle_registry.validate_registry(bad)  # duplicate cycle_id
    bad = _minimal_registry(_cycle_record(lifecycle="RETIRED"))
    with pytest.raises(atomic_io.SchemaValidationError):
        cycle_registry.validate_registry(bad)  # illegal lifecycle


