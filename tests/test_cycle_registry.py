# ------------------------------------------------- projection equality (M0)

def test_projection_is_deterministic_function_of_non_terminal_records(tmp_path):
    """The projection is produced ONLY by the writer and byte-equals its
    regeneration; terminal records never appear in it."""
    reg = _minimal_registry(
        _cycle_record("TEST-A", lifecycle="ACTIVE_LIGHT"),
        _cycle_record("TEST-B", lifecycle="TERMINAL",
                      go_phrase_state="DEAD (consumed at its gate)",
                      s0="CLOSED", heartbeat_utc=""),
    )
    reg["cycles"][1]["budget"] = {"used": 1, "max": 6}
    p = tmp_path / "CYCLE_REGISTRY.json"
    cycle_registry.save(p, reg)  # save regenerates the projection
    proj_path = tmp_path / "ACTIVE_CYCLES.json"
    assert proj_path.exists()
    assert cycle_registry.projection_matches(reg, proj_path.read_bytes())
    assert cycle_registry.write_projection(p, reg) == atomic_io.sha256_file(proj_path), \
        "regeneration must be byte-identical (deterministic)"
    rows = json.loads(proj_path.read_bytes().decode("utf-8"))["cycles"]
    assert [r["cycle_id"] for r in rows] == ["TEST-A"], "terminal records must never project"
    assert rows[0]["lifecycle"] == "ACTIVE_LIGHT"


def test_projection_drift_detects_hand_edits(tmp_path):
    reg = _minimal_registry()
    p = tmp_path / "CYCLE_REGISTRY.json"
    cycle_registry.save(p, reg)
    proj_path = tmp_path / "ACTIVE_CYCLES.json"
    hand_edited = json.loads(proj_path.read_bytes().decode("utf-8"))
    hand_edited["cycles"].append({"cycle_id": "GHOST"})
    proj_path.write_bytes((json.dumps(hand_edited, indent=1) + "\n").encode("utf-8"))
    assert not cycle_registry.projection_matches(reg, proj_path.read_bytes())
    assert cycle_registry.projection_drift(p, reg) is not None
    # and a plain byte rewrite (same JSON, different formatting) is drift too
    proj_path.write_bytes(proj_path.read_bytes().replace(b"\n ", b"\n  "))
    assert not cycle_registry.projection_matches(reg, proj_path.read_bytes())


def test_live_projection_matches_regeneration_or_is_detected_drift():
    """Live-tree check that tolerates regeneration: if the committed
    projection is in generated format it MUST byte-equal the regeneration
    from the canonical non-terminal records; if it is still a legacy
    hand-shaped file (pre-reconciliation state) the drift must be DETECTED,
    never silently accepted. No cycle name is ever hard-coded here."""
    reg = cycle_registry.load(REGISTRY)
    assert PROJECTION.exists(), "ACTIVE_CYCLES.json must exist"
    actual = PROJECTION.read_bytes()
    matches = cycle_registry.projection_matches(reg, actual)
    if matches:
        parsed = json.loads(actual.decode("utf-8"))
        assert parsed["schema"] == cycle_registry.PROJECTION_SCHEMA
        proj_ids = {r["cycle_id"] for r in parsed["cycles"]}
        expected_ids = {c["cycle_id"] for c in reg["cycles"]
                        if c["lifecycle"] not in cycle_registry.CLOSED}
        assert proj_ids == expected_ids
    else:
        # stale hand-shaped projection: doctor must label it, reconcile must
        # offer to regenerate it — the suite passes because drift is detected
        assert cycle_registry.projection_drift(REGISTRY, reg) is not None


def test_live_registry_invariants_hold_for_whatever_is_committed():
    """Single umbrella over the law for the live tree: valid schema, unique
    ids, disjoint active/closed, exact resolution. Passes for ANY legitimate
    registry content — including registries this test never saw."""
    reg = cycle_registry.load(REGISTRY)
    ids = [c["cycle_id"] for c in reg["cycles"]]
    assert len(ids) == len(set(ids))
    active = {c["cycle_id"] for c in cycle_registry.active_cycles(reg)}
    closed = {c["cycle_id"] for c in cycle_registry.closed_cycles(reg)}
    assert active.isdisjoint(closed)
    for cid in ids:
        assert cycle_registry.resolve(reg, cid)["cycle_id"] == cid


# ------------------ MDP-V2R1 A4 additive: declare_terminal_identity ---------

ANCHOR = "a" * 40
EVENTS = "CYCLE_REGISTRY.events.jsonl"


def _terminal_registry():
    return _minimal_registry(_cycle_record(
        lifecycle="TERMINAL", go_phrase_state="DEAD (consumed at its close)",
        heartbeat_utc=""))


def _saved_terminal_registry(tmp_path):
    reg = _terminal_registry()
    p = tmp_path / "CYCLE_REGISTRY.json"
    return p, cycle_registry.save(p, reg)


def _events(tmp_path):
    return atomic_io.read_events(tmp_path / EVENTS)


def test_declare_terminal_identity_happy_path_writes_row_and_journal(tmp_path):
    p, saved = _saved_terminal_registry(tmp_path)
    n_events = len(_events(tmp_path))
    rec, new_sha = cycle_registry.declare_terminal_identity(
        p, cycle_registry.load(p), prev_sha=saved, cycle_id="TEST-C1",
        terminal_anchor_sha=ANCHOR)
    assert rec["head"] == ANCHOR
    assert rec["head_semantics"] == "TERMINAL_ANCHOR"
    assert rec["terminal_anchor_sha"] == ANCHOR
    assert rec["post_terminal_policy"] == \
        "ALLOWLISTED_APPEND_ONLY_DESCENDANTS"
    events = _events(tmp_path)
    # the CAS save appends REGISTRY_SAVED, then the typed declaration event
    assert len(events) == n_events + 2
    declared = events[-1]
    assert declared["event"] == "TERMINAL_IDENTITY_DECLARED"
    assert declared["cycle_id"] == "TEST-C1"
    assert declared["terminal_anchor_sha"] == ANCHOR
    assert len([e for e in events
                if e["event"] == "TERMINAL_IDENTITY_DECLARED"]) == 1
    # the registry reloads schema-valid with the additive fields on board
    reloaded = cycle_registry.load(p)
    assert cycle_registry.resolve(reloaded, "TEST-C1")["head_semantics"] == \
        "TERMINAL_ANCHOR"
    cycle_registry.validate_registry(reloaded)
    assert new_sha == atomic_io.sha256_file(p)


def test_declare_terminal_identity_only_adds_the_three_fields(tmp_path):
    p, saved = _saved_terminal_registry(tmp_path)
    before = copy.deepcopy(cycle_registry.load(p))
    rec, _ = cycle_registry.declare_terminal_identity(
        p, cycle_registry.load(p), prev_sha=saved, cycle_id="TEST-C1",
        terminal_anchor_sha=ANCHOR, reason="audit-anchored closure")
    added = {k for k in rec if k not in before["cycles"][0]}
    assert added == {"head_semantics", "terminal_anchor_sha",
                     "post_terminal_policy"}
    # nothing pre-existing was rewritten (head/lifecycle untouched);
    # updated_at_utc is the writer's bookkeeping and is allowed to move
    for k, v in before["cycles"][0].items():
        if k == "updated_at_utc":
            continue
        assert rec[k] == v, k


def test_declare_terminal_identity_cas_mismatch_fails_closed(tmp_path):
    p, _saved = _saved_terminal_registry(tmp_path)
