"""Multi-symbol strategy scan with strict anti-overfit gates.

Pipeline:
  setup  - select the top-N liquid universe from a snapshot and write a frozen
           scan config (params are never tuned per symbol).
  run    - walk-forward every baseline strategy x symbol, one output JSON per
           combination so a failure cannot poison the whole matrix.
  report - aggregate all combinations, apply hard gates plus a Benjamini-
           Hochberg FDR correction on fold sign-tests, and rank survivors.

Usage:
  python -m research.scan_matrix setup --snapshot research_snapshots/binance_usdm_20260821.json --top 20
  python -m research.scan_matrix run --config config/research_scan_top20.yaml --folds 6 --workers 2
  python -m research.scan_matrix report --scan-dir results/scan_matrix/<stamp>
"""

from __future__ import annotations

import argparse
import json
import math
import sys
import time
from concurrent.futures import ProcessPoolExecutor, as_completed
from datetime import datetime, timezone
from pathlib import Path

BASELINE_TYPES = ("reclaim_mr", "trend_pullback", "markdown_breakdown")
MIN_ONBOARD_DAYS = 700


# --------------------------------------------------------------------------- #
# setup
# --------------------------------------------------------------------------- #
def select_universe(snapshot_path: str, top: int) -> list[dict]:
    data = json.loads(Path(snapshot_path).read_text(encoding="utf-8"))
    eligible = [
        c
        for c in data["contracts"]
        if c.get("eligible")
        and c.get("underlying_type") == "COIN"
        and c.get("onboard_days", 0) >= MIN_ONBOARD_DAYS
    ]
    eligible.sort(key=lambda c: (-c["quote_volume_24h"], c["symbol"]))
    return eligible[:top]


def cmd_setup(args: argparse.Namespace) -> int:
    import yaml

    universe = select_universe(args.snapshot, args.top)
    if len(universe) < args.top:
        print(
            f"warning: only {len(universe)} symbols satisfy onboard>={MIN_ONBOARD_DAYS}d",
            file=sys.stderr,
        )
    symbols = [c["symbol"] for c in universe]
    base_path = Path("config/research_baseline_altcoin.yaml")
    config = yaml.safe_load(base_path.read_text(encoding="utf-8"))
    config["market"]["symbols"] = symbols
    config["data"]["catalog_path"] = "./catalog_live_crypto"
    config["portfolio_risk"]["clusters"] = {
        c["symbol"]: c.get("cluster", "crypto") for c in universe
    }
    config["report"] = {
        "output_dir": "./results/scan_matrix",
        "include_csv": True,
        "include_json": True,
        "funding_data_path": args.funding_dir,
    }
    header = (
        f"# Auto-generated by scan_matrix setup {datetime.now(timezone.utc):%Y-%m-%d}.\n"
        f"# Universe: top-{args.top} liquidity with >={MIN_ONBOARD_DAYS}d history.\n"
        "# Params are frozen per asset class - never tuned per symbol.\n"
    )
    out = Path(args.out)
    out.write_text(header + yaml.safe_dump(config, sort_keys=False), encoding="utf-8")
    print(f"Universe ({len(symbols)}): {', '.join(symbols)}")
    print(f"Config: {out}")
    return 0


# --------------------------------------------------------------------------- #
# run
# --------------------------------------------------------------------------- #
def _run_one(job: tuple[str, str, str, int, str]) -> dict:
    """Worker: walk-forward one strategy x one symbol."""
    import warnings

    warnings.filterwarnings("ignore")
    config_path, strategy_type, symbol, folds, output = job
    from research.baseline_wf import run_walkforward

    started = time.monotonic()
    result = run_walkforward(
        config_path=config_path,
        strategy_type=strategy_type,
        symbols=(symbol,),
        folds=folds,
        output=output,
    )
    elapsed = time.monotonic() - started
    row = result["symbol_summary"][0]
    return {
        "strategy_type": strategy_type,
        "symbol": symbol,
        "summary": row,
        "cells": result["cells"],
        "elapsed_s": round(elapsed, 1),
    }


def cmd_run(args: argparse.Namespace) -> int:
    from config.settings import load_research_config

    settings = load_research_config(args.config)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    scan_dir = Path("results/scan_matrix") / stamp
    strategies = BASELINE_TYPES if not args.strategy else (args.strategy,)
    jobs: list[tuple[str, str, str, int, str]] = []
    for strategy_type in strategies:
        for symbol in settings.market.symbols:
            out = scan_dir / strategy_type / f"{symbol}.json"
            jobs.append((args.config, strategy_type, symbol, args.folds, str(out)))
    total = len(jobs)
    print(f"Scan matrix: {total} combos ({len(strategies)} strategies x "
          f"{len(settings.market.symbols)} symbols x {args.folds} folds)")
    workers = max(1, min(args.workers, total))
    results: list[dict] = []
    failures: list[str] = []
    done = 0
    with ProcessPoolExecutor(max_workers=workers) as pool:
        futures = {pool.submit(_run_one, job): job for job in jobs}
        for future in as_completed(futures):
            job = futures[future]
            label = f"{job[1]}/{job[2]}"
            try:
                res = future.result()
            except Exception as exc:  # noqa: BLE001
                failures.append(f"{label}: {exc}")
                print(f"[{done + 1}/{total}] FAIL  {label}: {exc}")
            else:
                results.append(res)
                row = res["summary"]
                status = "PASS" if row["passes_screen"] else "fail"
                print(
                    f"[{done + 1}/{total}] {status}  {label} "
                    f"folds={row['positive_after_funding']} "
                    f"exp={row['expectancy_after_funding']:+.4f} "
                    f"({res['elapsed_s']}s)",
                )
            done += 1
    index_path = scan_dir / "index.json"
    index_path.write_text(
        json.dumps(
            {
                "config": args.config,
                "stamp": stamp,
                "folds": args.folds,
                "strategies": list(strategies),
                "symbols": list(settings.market.symbols),
                "results": [
                    {"strategy_type": r["strategy_type"], "symbol": r["symbol"],
                     "file": str(scan_dir / r["strategy_type"] / f"{r['symbol']}.json")}
                    for r in results
                ],
                "failures": failures,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    print(f"Index: {index_path}")
    return 0 if not failures else 1


# --------------------------------------------------------------------------- #
# report
# --------------------------------------------------------------------------- #
def _binom_sf(k: int, n: int) -> float:
    """P(X >= k) for X ~ Binomial(n, 0.5); exact via Pascal's triangle."""
    total = 0.0
    coef = math.comb(n, k)
    p = 0.5 ** n
    for i in range(k, n + 1):
        total += coef * p
        coef = coef * (n - i) // (i + 1)
    return min(total, 1.0)


def _bh_adjust(pvalues: dict[str, float], q: float) -> dict[str, float]:
    m = len(pvalues)
    if m == 0:
        return {}
    ordered = sorted(pvalues.items(), key=lambda kv: kv[1])
    adjusted: dict[str, float] = {}
    prev = 1.0
    for rank in range(m, 0, -1):
        key, pv = ordered[rank - 1]
        val = min(prev, pv * m / rank)
        adjusted[key] = val
        prev = val
    return {k: (v if v <= q else 1.0) for k, v in adjusted.items()}


def cmd_report(args: argparse.Namespace) -> int:
    index = json.loads((Path(args.scan_dir) / "index.json").read_text(encoding="utf-8"))
    combos: list[dict] = []
    for entry in index["results"]:
        data = json.loads(Path(entry["file"]).read_text(encoding="utf-8"))
        row = data["symbol_summary"][0]
        cells = data["cells"]
        traded = [c for c in cells if c["trades"] > 0]
        pos_after = sum(1 for c in cells if c["positive_after_funding"])
        folds = index["folds"]
        wins_gross = sum(c.get("pnl_after_funding", 0.0) for c in traded if c["pnl_after_funding"] > 0)
        loss_gross = abs(sum(c.get("pnl_after_funding", 0.0) for c in traded if c["pnl_after_funding"] < 0))
        pf_after = wins_gross / loss_gross if loss_gloss_safe(loss_gross) else float("inf")
        p_value = _binom_sf(pos_after, folds)
        combos.append(
            {
                "strategy_type": entry["strategy_type"],
                "symbol": entry["symbol"],
                "trades": row["trades"],
                "positive_folds_after": f"{pos_after}/{folds}",
                "exp_after": row["expectancy_after_funding"],
                "pnl_after": row["pnl_after_funding"],
                "pf_after": round(pf_after, 3),
                "buy_hold": row["buy_hold_pnl_at_max_notional"],
                "p_value": p_value,
            },
        )

    tested = {
        f"{c['strategy_type']}:{c['symbol']}": c["p_value"]
        for c in combos
        if c["trades"] >= args.min_trades
    }
    adjusted = _bh_adjust(tested, args.fdr_q)

    gate_rows: list[dict] = []
    for c in combos:
        key = f"{c['strategy_type']}:{c['symbol']}"
        reasons = []
        if c["trades"] < args.min_trades:
            reasons.append("low_trades")
        pos, tot = c["positive_folds_after"].split("/")
        if int(pos) < math.ceil(int(tot) * 5 / 6):
            reasons.append("folds<5/6")
        if c["exp_after"] is None or c["exp_after"] <= 0:
            reasons.append("exp<=0")
        if c["pf_after"] <= args.min_pf:
            reasons.append("pf_low")
        if c["pnl_after"] is None or c["pnl_after"] <= c["buy_hold"]:
            reasons.append("no_edge_vs_bh")
        bh_q = adjusted.get(key)
        if bh_q is None:
            reasons.append("low_trades_fdr")
        elif bh_q > args.fdr_q:
            reasons.append("bh_fail")
        gate_rows.append({**c, "bh_q": bh_q, "gate": "PASS" if not reasons else "|".join(reasons)})

    gate_rows.sort(key=lambda r: r["p_value"])
    out_path = Path(args.scan_dir) / "report.json"
    out_path.write_text(json.dumps(gate_rows, indent=2), encoding="utf-8")

    passed = [r for r in gate_rows if r["gate"] == "PASS"]
    print(f"\n{'=' * 100}")
    print(f"SCAN REPORT — {len(gate_rows)} combos, {len(tested)} testable, "
          f"{len(passed)} PASS (gates: folds>=5/6, exp>0, PF>{args.min_pf}, "
          f"beat buy&hold, BH-FDR q<={args.fdr_q})")
    print("=" * 100)
    for r in gate_rows[:25]:
        marker = ">>>" if r["gate"] == "PASS" else "   "
        print(
            f"{marker} {r['strategy_type']:18s} {r['symbol']:14s} "
            f"folds={r['positive_folds_after']} exp={r['exp_after']:+.4f} "
            f"PF={r['pf_after']:.2f} PnL={r['pnl_after']:+9.2f} "
            f"BH={r['buy_hold']:+8.2f} p={r['p_value']:.3f} q={r['bh_q']} "
            f"[{r['gate']}]",
        )
    print(f"\nSaved: {out_path}")
    return 0


def loss_gloss_safe(value: float) -> bool:
    return value > 0


def main() -> int:
    parser = argparse.ArgumentParser(description="Multi-symbol baseline scan with FDR gates")
    sub = parser.add_subparsers(dest="command", required=True)

    p_setup = sub.add_parser("setup", help="select universe and write scan config")
    p_setup.add_argument("--snapshot", default="research_snapshots/binance_usdm_20260821.json")
    p_setup.add_argument("--top", type=int, default=20)
    p_setup.add_argument("--out", default="config/research_scan_top20.yaml")
    p_setup.add_argument("--funding-dir", default="./funding_data/scan_2026")
    p_setup.set_defaults(func=cmd_setup)

    p_run = sub.add_parser("run", help="walk-forward every strategy x symbol")
    p_run.add_argument("--config", default="config/research_scan_top20.yaml")
    p_run.add_argument("--strategy", choices=BASELINE_TYPES)
    p_run.add_argument("--folds", type=int, default=6)
    p_run.add_argument("--workers", type=int, default=2)
    p_run.set_defaults(func=cmd_run)

    p_report = sub.add_parser("report", help="aggregate + gate + rank")
    p_report.add_argument("--scan-dir", required=True)
    p_report.add_argument("--min-trades", type=int, default=30)
    p_report.add_argument("--min-pf", type=float, default=1.1)
    p_report.add_argument("--fdr-q", type=float, default=0.10)
    p_report.set_defaults(func=cmd_report)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
