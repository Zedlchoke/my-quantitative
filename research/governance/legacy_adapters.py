def file_sha256(path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def normalize_legacy_state(cycle_id: str, state: dict, *,
                           measured_branch_head: Optional[str] = None) -> dict:
    """Map one legacy state document to a cycle_registry@1 record (in memory).

    Raises KeyError for unknown cycle ids; callers must not invent records for
    cycles without a known authority.
    """
    warnings: list = []
    status = state.get("status")
    phase = state.get("phase") or ""
    if cycle_id == "STOCKS-FREE-V12":
        lifecycle = "TERMINAL"
    elif status == "TERMINAL":
        lifecycle = "TERMINAL"
    elif status is None and phase.startswith("CLOSED"):
        lifecycle = "TERMINAL"
        warnings.append(
            f"legacy status field absent; TERMINAL derived from the closure phase "
            f"{phase[:80]!r} (drift recorded-not-normalized per sec2)"
        )
    else:
        lifecycle = "PAUSED_MAINTENANCE" if state.get("hard_stop_reason") else None
        if lifecycle is None:
            lifecycle = {"ACTIVE_LIGHT": "ACTIVE_LIGHT", "ACTIVE_HEAVY": "ACTIVE_HEAVY"}.get(status)
            if lifecycle is None:
                raise KeyError(f"{cycle_id}: cannot derive lifecycle from legacy state")

    budget = state.get("budget")
    if isinstance(budget, dict) and "planned" in budget:  # forex legacy shape
        budget_out = {"used": budget.get("used", 0), "max": budget.get("planned", 0)}
        if budget.get("bound_by_selection") is not None:
            budget_out["bound_by_selection"] = budget["bound_by_selection"]
    else:  # v17 / v12 shape: budget_used / budget_max
        budget_out = {"used": state.get("budget_used", 0), "max": state.get("budget_max", 0)}

    head = measured_branch_head or ""
    legacy_head = state.get("head")
    if isinstance(legacy_head, str) and len(legacy_head) == 40 and legacy_head != head:
        warnings.append(
            f"legacy state head {legacy_head} is stale vs measured branch head {head} "
            "(drift recorded-not-normalized per sec2; see pause packet)"
        )
    elif isinstance(legacy_head, str) and legacy_head and len(legacy_head) != 40:
        warnings.append(
            f"legacy state head is prose ({legacy_head[:48]!r}) - unusable as authority; "
            "measured branch head used (drift recorded-not-normalized per sec2)"
        )

    return {
        "cycle_id": cycle_id,
        "asset": ASSET_BY_CYCLE[cycle_id],
        "plan": state.get("plan", PLAN_BY_CYCLE[cycle_id]),
        "lifecycle": lifecycle,
        "phase": state.get("phase") or state.get("status", ""),
        "integration_worktree": str(main_repo_root() / WORKTREE_BY_CYCLE[cycle_id]),
        "branch": BRANCH_BY_CYCLE[cycle_id],
        "head": head,
        "budget": budget_out,
        "denominators": dict(DENOMINATORS_BY_CYCLE[cycle_id]),
        "s0": "CLOSED" if lifecycle == "TERMINAL" else "OPEN",
        "s1": state.get("s1", "SEALED_UNTOUCHED"),
        "go_phrase": state.get("go_phrase", ""),
        "go_phrase_state": ("DEAD (extinguished unconsumed with its closed cycle per P-8 / RULES §7)"
                            if lifecycle == "TERMINAL"
                            else (state.get("go_phrase_state") or state.get("go_state", ""))),
        "workers": state.get("workers", 0),
        "active_heavy": bool(state.get("active_heavy", False)),
        "lock": state.get("heavy_lock", "machine-wide heavy lock (see researchctl locks inspect)"),
        "heartbeat_utc": state.get("updated_at_utc") or state.get("updated_utc", ""),
        "hard_stop_reason": state.get("hard_stop_reason"),
        "pause_packet": PACKET_BY_CYCLE[cycle_id],
        "next_authorized_action": state.get("next_safe_action") or (
            "NONE (closed; stocks continuation is a later owner decision)"
            if lifecycle == "TERMINAL" else ""),
        "updated_at_utc": cycle_registry.now_utc(),
        "adapter_warnings": warnings,
    }


def build_registry_from_legacy(measured_heads: dict) -> dict:
    """Compose a full cycle_registry@1 from the three legacy state files.

    `measured_heads` maps cycle_id -> branch head measured by the caller
    (git rev-parse). Known closed cycles come from HISTORICAL_CLOSED (the H1
    freeze inventory), never from guessed worktrees.
    """
    cycles = []
    for cid in ("CRYPTO-V17", "FOREX-FREE-V8", "STOCKS-FREE-V12"):
        path = main_repo_root() / LEGACY_SOURCES[cid]
        state = json.loads(path.read_bytes().decode("utf-8"))
        cycles.append(normalize_legacy_state(cid, state, measured_branch_head=measured_heads[cid]))
    for cid, meta in HISTORICAL_CLOSED.items():
        asset = ("crypto" if cid.startswith("CRYPTO")
                 else "forex" if cid.startswith("FOREX") else "stocks")
        cycles.append({
            "cycle_id": cid, "asset": asset, "plan": meta["plan"],
            "lifecycle": "TERMINAL", "phase": "historical closed (registry lookup entry)",
            "integration_worktree": "", "branch": "", "head": meta["head"],
            "budget": {"used": 0, "max": 0},
            "denominators": {"note": "see HYPOTHESIS_LEDGER.md (P-9)"},
            "s0": "CLOSED", "s1": "SEALED_UNTOUCHED", "go_phrase": "",
            "go_phrase_state": "DEAD (consumed or extinguished with its closed cycle)",
            "workers": 0, "active_heavy": False, "lock": "n/a", "heartbeat_utc": "",
            "hard_stop_reason": None, "pause_packet": None,
            "next_authorized_action": "NONE (closed)",
            "updated_at_utc": cycle_registry.now_utc(), "adapter_warnings": [],
        })
    return {
        "schema": cycle_registry.SCHEMA_ID,
        "updated_at_utc": cycle_registry.now_utc(),
        "writer": "researchctl build-from-legacy",
        "write_token": None,
        "cycles": cycles,
    }
