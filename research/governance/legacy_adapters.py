def main_repo_root() -> Path:
    """Absolute path of the MAIN checkout (owner space).

    Nested cycle worktrees and their control files exist only under the main
    checkout; any SHV1 lane worktree sees them as gitignored paths that do not
    exist locally. Resolves via the shared .git dir, never via cwd.
    """
    common = subprocess.run(
        ["git", "rev-parse", "--path-format=absolute", "--git-common-dir"],
        capture_output=True, text=True, check=True,
    ).stdout.strip()
    return Path(common).parent


