"""gen_fixtures — JF2 synthetic calendar (deterministic; commit outputs).

The JF2 host is JF1 (single-host draft, option J-A shape). The panel and base
calendar are the JF1 synthetic fixtures (regenerated by the same deterministic
code path, never copied by hand); the JF2 addition is the synthetic MOF op
table: op_date + disclosure_date (~1 month lag per DC s.1.4) + amount.
"""
from __future__ import annotations

import json
from pathlib import Path

from jf1_boj_mpm.fixtures.gen_fixtures import build_calendar, build_panel, MPM_DATES

HERE = Path(__file__).resolve().parent

# Synthetic ops (NOT real MOF data). op A lands on the TP-hit MPM day and is
# DISCLOSED a month later — the PIT boundary this family exists to enforce.
# Ops B/C disclose even later so the op-day PIT probe has NO visible op.
OPS = [
    {"op_date": "2026-02-15", "disclosure_date": "2026-03-15", "amount_jpy_bn": 4200},
    {"op_date": "2026-01-15", "disclosure_date": "2026-04-14", "amount_jpy_bn": 2600},
    {"op_date": "2025-12-15", "disclosure_date": "2026-05-13", "amount_jpy_bn": 5100},
]


def build_ops() -> list[dict]:
    return [dict(o) for o in OPS]


def main() -> None:
    panel = build_panel()
    calendar = build_calendar()
    calendar["mof_ops"] = build_ops()
    with open(HERE / "jf2_panel_host.json", "w", encoding="utf-8") as fh:
        json.dump(panel, fh, indent=0)
    with open(HERE / "jf2_calendar.json", "w", encoding="utf-8") as fh:
        json.dump(calendar, fh, indent=1)
    print("bars", len(panel["bars"]), "sessions", len(panel["sessions"]),
          "ops", len(OPS), "first_mpm", MPM_DATES[0])


if __name__ == "__main__":
    main()
