"""ILLIQ-REG-V1 frozen regime gate — plan plans/PLAN_illiq_reg_gate_v1.md SS3.

Pure functions over caller-supplied daily aggregates so M0 tests run offline
on hand fixtures. The full-catalog gate-series build lives in
gate_series_build.py and runs under the heavy lock (gate-sequence step 3).

Definition note (binding): the frozen thresholds were generated by the
dossier's pit_conc_gate_single_shot.py, which defines CONC(w) = mean of the
DAILY PIT DV-share over the trailing w days ending strictly before the stamp,
and S90 = CONC(28) - CONC(90). This module reproduces that definition
exactly; any other reading of the prereg prose would silently invalidate the
threshold semantics and is forbidden.

Window semantics: a daily block at date d is usable at stamp T iff
d < T (completed UTC blocks strictly before T); rvol30 likewise uses the last
30 completed closes with close-date <= last day strictly before T, matching
the dossier code at Monday 00:00Z stamps.
"""
from __future__ import annotations

import datetime as dt
import hashlib
import math
import random
from dataclasses import dataclass

UTC = dt.timezone.utc

# --- frozen constants (PREREG draft + plan SS3; never tuned in-cycle) -------
BAND_ON_S90 = 0.021317    # p70 of pre-window Mondays 2020-01-06..2024-08-19, n=242
BAND_OFF_S90 = 0.057702   # p90 of the same set
VOL_FLOOR = 0.328930      # p10 of pre-window Mondays, n=238
VOL_HYST_FRAC = 0.10
VOL_OFF = 0.296037        # = VOL_FLOOR * (1 - VOL_HYST_FRAC), as frozen
INITIAL_STATE = True      # both state machines start ON
CONC_WINDOW_DAYS = 28
S90_WINDOW_DAYS = 90
RVOL_WINDOW = 30
LISTING_AGE_DAYS = 28     # same listing-age law as the frozen engine

# falsification bar (plan SS6, verbatim)
FALSIFICATION_NET_BAR = -0.2947   # >= 50% improvement vs -0.589312
FALSIFICATION_MDD_BAR = 0.4372    # <= 30% reduction vs 0.624507

# random-gate controls (plan SS7)
RANDOM_GATE_N = 200
RANDOM_GATE_MIN_RUN = 4
CYCLE_ID = "ILLIQ-REG-V1"


def seed_from_cycle_id(cycle_id: str = CYCLE_ID) -> int:
    """Declared, reproducible RNG seed derived from the cycle id string."""
    return int.from_bytes(hashlib.sha256(cycle_id.encode()).digest()[:8], "big")


# --- PIT daily aggregation ---------------------------------------------------

def daily_dv_share(
    dv: dict[tuple[dt.date, str], float],
    first_day: dict[str, dt.date],
    *,
    listing_age_days: int = LISTING_AGE_DAYS,
) -> dict[dt.date, float]:
    """BTC share of DV over PIT-eligible symbols per day.

    A symbol is eligible on day d iff it has >= listing_age_days of prior
    daily blocks (first_day <= d - listing_age_days) and has DV that day.
    """
    days = sorted({d for d, _ in dv})
    out: dict[dt.date, float] = {}
    for d in days:
        eligible = [
            s for s in first_day
            if first_day[s] <= d - dt.timedelta(days=listing_age_days)
            and dv.get((d, s))
        ]
        if not eligible or "BTCUSDT" not in eligible:
            continue
        total = math.fsum(dv[(d, s)] for s in eligible)
        if total <= 0:
            continue
        out[d] = dv[(d, "BTCUSDT")] / total
    return out


def conc_mean(share: dict[dt.date, float], stamp: dt.date, window_days: int):
    """Mean daily DV-share over [stamp - window_days, stamp); None if empty."""
    lo = stamp - dt.timedelta(days=window_days)
    vals = [share[x] for x in sorted(share) if lo <= x < stamp]
    return math.fsum(vals) / len(vals) if vals else None


def s90_at(share: dict[dt.date, float], stamp: dt.date):
    """S90(T) = CONC(28) - CONC(90), the frozen dossier definition."""
    c28 = conc_mean(share, stamp, CONC_WINDOW_DAYS)
    c90 = conc_mean(share, stamp, S90_WINDOW_DAYS)
    if c28 is None or c90 is None:
        return None
    return c28 - c90


def rvol30(closes: dict[dt.date, float], stamp: dt.date,
           window: int = RVOL_WINDOW):
    """Annualized realized vol: pstdev of `window` daily log closes * sqrt(365).

    Uses the last window+1 completed closes with date < stamp; None if
    insufficient history (fail-closed: caller decides, never imputes).
    """
    ds = [x for x in sorted(closes) if x < stamp][-(window + 1):]
    if len(ds) < window + 1:
        return None
    rs = [math.log(closes[ds[i + 1]] / closes[ds[i]]) for i in range(window)]
    return statistics_pstdev(rs) * math.sqrt(365)


def statistics_pstdev(values):
    return math.sqrt(math.fsum((v - _mean(values)) ** 2 for v in values) / len(values))


def _mean(values):
    return math.fsum(values) / len(values)


# --- hysteresis state machines ------------------------------------------------

def v1_next_state(s90_value, prev_state: bool) -> bool:
    """ON if S90 <= p70; OFF if S90 >= p90; carry between; carry on None."""
    if s90_value is None:
        return prev_state
    if s90_value >= BAND_OFF_S90:
        return False
    if s90_value <= BAND_ON_S90:
        return True
    return prev_state


def v2_next_state(vol_value, prev_state: bool) -> bool:
    """ON if VOL >= floor; OFF if VOL < floor*(1-hyst); carry between/None."""
    if vol_value is None:
        return prev_state
    if vol_value >= VOL_FLOOR:
        return True
    if vol_value < VOL_OFF:
        return False
    return prev_state


@dataclass
class GateWalkRow:
    stamp: dt.date
    s90: float | None
    rvol: float | None
    v1_state: bool
    v2_state: bool
    gated: bool


def gate_walk(rows: dict[dt.date, tuple]) -> dict[dt.date, GateWalkRow]:
    """Full walk in stamp order; both machines start ON; GATED = V1 AND V2.

    rows: stamp -> (s90 | None, rvol | None).
    """
    v1 = INITIAL_STATE
    v2 = INITIAL_STATE
    out: dict[dt.date, GateWalkRow] = {}
    for stamp in sorted(rows):
        s, rv = rows[stamp]
        v1 = v1_next_state(s, v1)
        v2 = v2_next_state(rv, v2)
        out[stamp] = GateWalkRow(stamp, s, rv, v1, v2, v1 and v2)
    return out


# --- falsification verdict (plan SS6) -----------------------------------------

def falsification_verdict(gated_net_sum: float, gated_mdd: float) -> dict:
    """FALSIFIED unless BOTH bars hold; margins-to-fail recorded (P-2)."""
    net_ok = gated_net_sum >= FALSIFICATION_NET_BAR
    mdd_ok = gated_mdd <= FALSIFICATION_MDD_BAR
    return {
        "verdict": "PASS_BAR" if (net_ok and mdd_ok) else "FALSIFIED",
        "net_bar": FALSIFICATION_NET_BAR,
        "mdd_bar": FALSIFICATION_MDD_BAR,
        "net_margin": gated_net_sum - FALSIFICATION_NET_BAR,
        "mdd_margin": FALSIFICATION_MDD_BAR - gated_mdd,
        "net_ok": net_ok,
        "mdd_ok": mdd_ok,
    }


# --- random-gate controls (plan SS7) ------------------------------------------

def _random_runs(n_total: int, n_runs: int, min_run: int, rng: random.Random):
    """Run-length composition of n_total into n_runs parts, each >= min_run.

    Deterministic given rng. Unit-at-a-time weighted allocation: always valid,
    O(leftover), no rejection loop.
    """
    if n_runs < 1 or n_runs * min_run > n_total:
        raise ValueError("infeasible composition: n_runs*min_run > n_total")
    parts = [min_run] * n_runs
    leftover = n_total - min_run * n_runs
    while leftover > 0:
        weights = [rng.random() + 1e-9 for _ in range(n_runs)]
        best = max(range(n_runs), key=lambda i: weights[i])
        parts[best] += 1
        leftover -= 1
    return parts


def gate_from_runs(runs, start_state: bool = INITIAL_STATE):
    """Expand run lengths into a boolean gate series (alternating runs)."""
    series = []
    state = start_state
    for run in runs:
        series.extend([state] * run)
        state = not state
    return series


def random_gate_permutations(gate_series, n: int = RANDOM_GATE_N,
                             min_run: int = RANDOM_GATE_MIN_RUN,
                             seed: int | None = None):
    """Seeded permutations preserving length, toggle count, min run >= min_run.

    The starting state is preserved (frozen walk starts ON). Deterministic:
    same (gate_series, n, seed) -> same list.
    """
    if not gate_series:
        raise ValueError("empty gate series")
    rng = random.Random(seed_from_cycle_id() if seed is None else seed)
    start_state = bool(gate_series[0])
    n_total = len(gate_series)
    toggles = sum(1 for a, b in zip(gate_series, gate_series[1:]) if a != b)
    n_runs = toggles + 1
    out = []
    for _ in range(n):
        runs = _random_runs(n_total, n_runs, min_run, rng)
        out.append(gate_from_runs(runs, start_state))
    return out


def gate_rank_percentile(gated_net: float, random_nets) -> float:
    """Percentile rank of the gated result among random-gate nets (0..100)."""
    vals = sorted(random_nets)
    if not vals:
        raise ValueError("no random nets")
    below = sum(1 for v in vals if v < gated_net)
    return 100.0 * below / len(vals)
